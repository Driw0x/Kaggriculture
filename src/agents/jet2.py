def _project_shed(obs, action, configuration):
    """Mirror worker-order DROP/PLACE/PICKUP, including shared shed capacity."""
    private = _get(obs, "private", {}) or {}
    shed = dict(_get(private, "shed", {}) or {})
    inventories = copy.deepcopy(_get(private, "inventories", []) or [])
    farm = copy.deepcopy(_farm(obs, _seat(obs)))
    positions = [_get(farm, "farmer"), *(_get(farm, "hands", []) or [])]
    commands = [action["farmer"], *action["hands"]]
    capacity = int(_get(configuration, "shedCapacity", 100))
    for position, inv, command in zip(positions, inventories, commands):
        if not command or not _shed_access(position, configuration):
            continue
        op = command[0]
        item = command[1] if len(command) > 1 else None
        qty = max(0, int(command[2])) if len(command) > 2 else 1
        if op == "PICKUP" and item:
            take = min(qty, shed.get(item, 0))
            if take > 0:
                shed[item] = shed.get(item, 0) - take
                inv[item] = inv.get(item, 0) + take
            continue
        if op == "PLACE" and item:
            tile = _tile_at(farm, position)
            structure = {"COW": "PASTURE", "SHEEP": "PASTURE", "GOOSE": "COOP"}.get(item)
            if structure and isinstance(tile, dict) and tile.get("kind") == structure and "animal" not in tile:
                if inv.get(item, 0) > 0:
                    tile["animal"] = item  # Later actors see the occupied tile.
                    inv[item] -= 1
                continue
            deposits = [(item, min(qty, inv.get(item, 0)))]
        elif op == "DROP":
            deposits = list(inv.items())
        else:
            continue
        for product, quantity in deposits:
            take = min(max(0, quantity), max(0, capacity - sum(shed.values())))
            if take > 0:
                shed[product] = shed.get(product, 0) + take
    return shed


def _opponent_supply(obs, configuration, horizon=8):
    """Heuristic, not hidden inventory: visible harvests close to a worker.

    Also include the next animal production if it falls within the horizon.
    Worker intentions and feeding next turn remain unknown.
    """
    farm = _farm(obs, 1 - _seat(obs))
    step = int(_get(obs, "step", 0))
    turns = max(1, int(_get(configuration, "turnsPerDay", 24)))
    day = int(_get(obs, "day", step // turns))
    workers = [_get(farm, "farmer"), *(_get(farm, "hands", []) or [])]
    exposure = dict.fromkeys(_PREMIUM, 0.0)
    for y, row in enumerate(_get(farm, "tiles", []) or []):
        for x, tile in enumerate(row):
            if not isinstance(tile, dict):
                continue
            product = tile.get("crop") or _ANIMAL_PRODUCT.get(tile.get("animal"))
            if product not in exposure:
                continue
            distance = min((abs(p[0] - x) + abs(p[1] - y) for p in workers if p is not None), default=100)
            if distance > horizon // 2:
                continue
            units = max(0, int(tile.get("yield_units", 0)))
            if tile.get("crop") and day - tile.get("planted_day", day) < _CROP_MATURITY[product]:
                units = 0
            animal = tile.get("animal")
            if animal in _ANIMAL_TIMING and turns - step % turns <= horizon:
                first, interval, cap = _ANIMAL_TIMING[animal]
                age = day + 1 - tile.get("placed_day", day) - first
                survives = tile.get("fed_today") or tile.get("consecutive_unfed", 0) < 1
                if survives and age >= 0 and age % interval == 0:
                    bonus = tile.get("pending_care_bonus", 0) if tile.get("fed_today") else 0
                    units = min(cap, units + 1 + bonus)
            exposure[product] += units / (1.0 + distance / 4.0)
    return exposure


def _update_expert(obs, configuration):
    """Three market experts, daily decisions and a two-day minimum dwell."""
    seat, step = _seat(obs), int(_get(obs, "step", 0))
    turns = max(1, int(_get(configuration, "turnsPerDay", 24)))
    state = _MARKET_STATE.get(seat)
    if state is None or step == 0 or step < state["last_step"]:
        state = {"mode": "BASE", "since": step, "last_step": step, "decision_day": -1,
                 "supply": {}, "switches": 0, "extra_orders": 0, "errors": {},
                 "pending": {}, "deferred_units": 0, "settled_units": 0,
                 "near_streak": 0, "clone_latched": False, "route_due": {},
                 "preempted_units": 0, "repaid_units": 0}
        _MARKET_STATE[seat] = state
    distance = _public_farm_distance(obs)
    state["near_streak"] = state.get("near_streak", 0) + 1 if distance <= 2 else 0
    if step >= 48 and state["near_streak"] >= 24:
        state["clone_latched"] = True
    elapsed = max(0, step - state["last_step"])
    weight = 1.0 - 0.75 ** elapsed
    visible = _opponent_supply(obs, configuration)
    for item, units in visible.items():
        previous = state["supply"].get(item, units)
        state["supply"][item] = (1 - weight) * previous + weight * units
    state["last_step"] = step
    day = step // turns
    if state["decision_day"] == day:
        return state
    state["decision_day"] = day
    if day < 12 or step - state["since"] < 2 * turns:
        return state
    risk = sum(state["supply"].values())
    inventory = _get(_get(obs, "market", {}), "inventory", {})
    shops = _get(_get(obs, "town", {}), "unlocked_shops", []) or []
    recovering = any(
        any(item in _SHOP_PRODUCTS.get(shop, ()) for shop in shops)
        and _market_price(item, _get(inventory, item, 10000), obs, configuration)
        < 0.8 * _params(item, obs, configuration)["base"] for item in _PREMIUM)
    if risk >= 12 or (state["mode"] == "COLLISION" and risk > 4):
        mode = "COLLISION"
    elif recovering and risk < 4:
        mode = "PATIENCE"
    else:
        mode = "BASE"
    if mode != state["mode"]:
        state["mode"], state["since"] = mode, step
        state["switches"] += 1
    return state


def _public_farm_distance(obs):
    """Small identity-free distance over visible route-relevant assets."""
    farms = list(_get(obs, "farms", []) or [])
    if len(farms) < 2:
        return float("inf")
    def signature(farm):
        counts = {}
        for row in _get(farm, "tiles", []) or []:
            for tile in row:
                if not isinstance(tile, dict):
                    continue
                for key in ("kind", "crop", "animal"):
                    value = tile.get(key)
                    if value:
                        counts[value] = counts.get(value, 0) + 1
        counts["HANDS"] = len(_get(farm, "hands", []) or [])
        counts["LAND"] = len(_get(farm, "unlocked_quadrants", []) or [])
        return counts
    left, right = map(signature, farms[:2])
    return float(sum(abs(left.get(key, 0) - right.get(key, 0)) for key in set(left) | set(right)))


def _clone_route_preemption(obs, action, configuration, state, actions=None, horizon=2):
    """Advance a bounded own-route sale against a persistently similar farm."""
    actions = actions or _LEGACY_ACTIONS
    result = _copy_action(action)
    step = int(_get(obs, "step", 0))
    due = state.setdefault("route_due", {})
    due_now = dict(due.pop(step, {}) or {})
    adjusted = []
    for order in result["market"]:
        order = list(order)
        if _is_sell(order) and due_now.get(order[1], 0) > 0:
            reduction = min(max(0, int(order[2])), due_now[order[1]])
            order[2] -= reduction
            due_now[order[1]] -= reduction
            state["repaid_units"] = state.get("repaid_units", 0) + reduction
        if not _is_sell(order) or int(order[2]) > 0:
            adjusted.append(order)
    result["market"] = adjusted
    # Carry debt only to the next tick when the expected sale was unavailable.
    for item, quantity in due_now.items():
        if quantity > 0 and step + 1 < len(actions):
            row = due.setdefault(step + 1, {})
            row[item] = row.get(item, 0) + quantity

    limit = max(1, int(_get(configuration, "maxMarketOrdersPerTurn", 10)))
    if (not state.get("clone_latched") or _public_farm_distance(obs) > 2
            or step < 160 or step + horizon >= len(actions)
            or len(result["market"]) >= limit):
        return result
    future = {}
    for order in (actions[step + horizon] or {}).get("market", []) or []:
        if _is_sell(order):
            future[order[1]] = future.get(order[1], 0) + max(0, int(order[2]))
    if not future:
        return result
    shed = _project_shed(obs, result, configuration)
    existing = {}
    for order in result["market"]:
        if _is_sell(order):
            existing[order[1]] = existing.get(order[1], 0) + max(0, int(order[2]))
    prices = _get(_get(obs, "market", {}), "prices", {})
    candidates = []
    for item, planned in future.items():
        quantity = min(10, planned, max(0, int(shed.get(item, 0)) - existing.get(item, 0)))
        if quantity > 0:
            candidates.append((float(_get(prices, item, 0)) * quantity, item, quantity))
    candidates.sort(reverse=True)
    remaining = 10
    for _, item, quantity in candidates:
        if remaining <= 0 or len(result["market"]) >= limit:
            break
        quantity = min(quantity, remaining)
        result["market"].append(["SELL", item, quantity])
        row = due.setdefault(step + horizon, {})
        row[item] = row.get(item, 0) + quantity
        state["preempted_units"] = state.get("preempted_units", 0) + quantity
        remaining -= quantity
    return result


def _is_sell(order):
    return len(order) >= 3 and order[0] == "SELL" and order[1] in _MARKET_PARAMS


def _jet1_market_price(item, inventory):
    base, equilibrium, scale, below_func, below_target, above_func, above_target = _JET1_MARKET_PARAMS[item]
    if inventory < equilibrium:
        amplitude = below_target * base / _shape(below_func, scale)
        price = base + amplitude * _shape(below_func, equilibrium - inventory)
    else:
        amplitude = above_target * base / _shape(above_func, scale)
        price = base - amplitude * _shape(above_func, inventory - equilibrium)
    return max(1, int(round(price)))


def _jet1_order_score(obs, configuration, order):
    if not _is_sell(order):
        return float("-inf")
    item = str(order[1])
    quantity = max(0, int(order[2]))
    market = _get(obs, "market", {}) or {}
    inventory = _get(market, "inventory", {}) or {}
    prices = _get(market, "prices", {}) or {}
    current_inventory = int(_get(inventory, item, 10000) or 0)
    current_quote = float(_get(prices, item, _jet1_market_price(item, current_inventory)) or 0)
    later_quote = float(_jet1_market_price(item, current_inventory + quantity))
    score = float(quantity) * max(0.0, current_quote - later_quote)
    if _regime(configuration) != "rebalance" or score <= 0:
        return score
    demand = max(0.25, _demand_per_day_jet1(obs, configuration, item))
    excess = max(0.0, current_inventory + quantity - 10000)
    urgency = min(1.0, (excess / demand) / 10.0)
    return score * (1.0 + 0.25 * urgency)


def _demand_per_day_jet1(obs, configuration, item):
    turns = int(_get(configuration, "turnsPerDay", 24) or 24)
    shop_interval = max(1, int(_get(configuration, "townShopSellInterval", 4) or 4))
    demand = 0.0
    for shop in _get(_get(obs, "town", {}), "unlocked_shops", []) or []:
        products = _SHOP_PRODUCTS.get(shop, ())
        if item in products:
            demand += (turns / shop_interval) * (2 if len(products) == 1 else 1)
    if item != "FERTILIZER":
        center_default = 24 if _regime(configuration) == "rebalance" else 12
        center = max(1, int(_get(configuration, "townCenterSellInterval", center_default) or center_default))
        day = int(_get(obs, "day", int(_get(obs, "step", 0)) // 24) or 0)
        multiplier = 1 if _regime(configuration) == "rebalance" else (4 if day >= 20 else 2 if day >= 10 else 1)
        demand += (turns / center) * multiplier
    return demand


def _jet1_rank_sell_slots(obs, action, configuration):
    """Preserve Jet1's empirically stronger ranking while testing other axes."""
    result = _copy_action(action)
    rows = [(_jet1_order_score(obs, configuration, order), -index, list(order))
            for index, order in enumerate(result["market"]) if _is_sell(order)]
    if len(rows) < 2:
        return result
    rows.sort(reverse=True)
    ranked = iter(row[2] for row in rows)
    result["market"] = [next(ranked) if _is_sell(order) else order for order in result["market"]]
    return result


def _rank_sell_runs(obs, action, configuration, supply):
    """Reorder only contiguous SELL runs: never cross a BUY/HIRE funding edge."""
    result = _copy_action(action)
    inventory = _get(_get(obs, "market", {}), "inventory", {})
    def score(order):
        item = order[1]
        qty = min(int(_get(configuration, "shedCapacity", 100)), max(0, int(order[2])))
        stock = _get(inventory, item, _params(item, obs, configuration)["I0"])
        now, _ = _sale_value(item, stock, qty, obs, configuration)
        later, _ = _sale_value(item, stock + supply.get(item, 0), qty, obs, configuration)
        return now - later
    start = 0
    while start < len(result["market"]):
        if not _is_sell(result["market"][start]):
            start += 1
            continue
        stop = start + 1
        while stop < len(result["market"]) and _is_sell(result["market"][stop]):
            stop += 1
        run = result["market"][start:stop]
        # Repeated products have sequential supply effects; retain their route
        # order rather than scoring each against the same starting inventory.
        if len({order[1] for order in run}) == len(run):
            result["market"][start:stop] = sorted(run, key=score, reverse=True)
        start = stop
    return result


def _post_demand_shift(obs, action, configuration, state):
    """Defer at most ten available units by one tick when demand lifts proceeds.

    No financing orders on either tick, no day-boundary deferral, at least
    twenty free shed slots after sales, and no deferral of feed/fertilizer.
    Pending sales are real quantities, never encoded or future opponent orders.
    """
    result = _copy_action(action)
    step = int(_get(obs, "step", 0))
    pending = state.setdefault("pending", {})
    settling = any(debt["due"] <= step for debt in pending.values())
    limit = max(1, int(_get(configuration, "maxMarketOrdersPerTurn", 10)))
    shed = _project_shed(obs, result, configuration)
    for item, debt in list(pending.items()):
        if debt["due"] > step:
            continue
        existing = next((o for o in result["market"] if _is_sell(o) and o[1] == item), None)
        reserved = sum(max(0, int(o[2])) for o in result["market"] if _is_sell(o) and o[1] == item)
        qty = min(debt["quantity"], max(0, shed.get(item, 0) - reserved))
        if qty and (existing is not None or len(result["market"]) < limit):
            if existing is not None:
                existing[2] += qty
            else:
                result["market"].append(["SELL", item, qty])
            state["settled_units"] = state.get("settled_units", 0) + qty
            debt["quantity"] -= qty
        # If an existing route sale already covers these units, no additional
        # sale is needed. Otherwise retry while they remain in the shed.
        if debt["quantity"] <= 0 or shed.get(item, 0) <= reserved:
            del pending[item]
    if settling or pending or not result["market"] or any(not _is_sell(o) for o in result["market"]):
        return result
    turns = max(1, int(_get(configuration, "turnsPerDay", 24)))
    final = int(_get(configuration, "episodeSteps", 720)) - 2
    if step % turns == turns - 1 or step >= min(final - 1, len(_LEGACY_ACTIONS) - 1):
        return result
    next_orders = _LEGACY_ACTIONS[step + 1]["market"]
    if any(not _is_sell(o) for o in next_orders):
        return result
    demand = _demand_on_tick(obs, configuration, step)
    inventory = _get(_get(obs, "market", {}), "inventory", {})
    remaining = dict(shed)
    for order in result["market"]:
        remaining[order[1]] = max(0, remaining.get(order[1], 0) - int(order[2]))
    capacity = int(_get(configuration, "shedCapacity", 100))
    for order in result["market"]:
        item = order[1]
        if item not in _PREMIUM or demand[item] <= 0:
            continue
        if sum(o[1] == item for o in result["market"]) != 1:
            continue
        if len(next_orders) >= limit and not any(o[1] == item for o in next_orders):
            continue
        actual = min(max(0, int(order[2])), max(0, shed.get(item, 0)))
        held = min(10, actual, max(0, capacity - 20 - sum(remaining.values())))
        if held <= 0:
            continue
        stock = _get(inventory, item, _params(item, obs, configuration)["I0"])
        _, after_partial = _sale_value(item, stock, actual - held, obs, configuration)
        immediate, _ = _sale_value(item, after_partial, held, obs, configuration)
        # PATIENCE allows weaker evidence, COLLISION needs a larger margin.
        incoming = state["supply"].get(item, 0)
        delayed, _ = _sale_value(item, after_partial + incoming - demand[item], held, obs, configuration)
        margin = 5 if state["mode"] == "COLLISION" else 1
        if delayed - immediate <= margin:
            continue
        order[2] = actual - held
        pending[item] = {"due": step + 1, "quantity": held}
        state["deferred_units"] = state.get("deferred_units", 0) + held
        result["market"] = [o for o in result["market"] if int(o[2]) > 0]
        break  # One bounded timing change per tick.
    return result


def _market_overlay(obs, action, configuration, state):
    step = int(_get(obs, "step", 0))
    turns = max(1, int(_get(configuration, "turnsPerDay", 24)))
    if step < 12 * turns:
        return action  # Preserve opening finance as well as worker actions.
    result = _post_demand_shift(obs, action, configuration, state)
    result = _rank_sell_runs(obs, result, configuration, state["supply"])
    return _idle_market_sales(obs, result, configuration, state)


def _idle_market_sales(obs, result, configuration, state):
    """Add only the opportunistic sales part of the market overlay."""
    result = _copy_action(result)
    step = int(_get(obs, "step", 0))
    # Add sales only to otherwise market-idle ticks. This avoids displacing a
    # route buy/hire, and avoids changing its shared-market execution index.
    if result["market"]:
        return result
    shed = _project_shed(obs, result, configuration)
    inventory = _get(_get(obs, "market", {}), "inventory", {})
    consumed = _demand_on_tick(obs, configuration, step - 1)
    candidates = []
    for item in _PREMIUM:  # WHEAT/feed and fertilizer are reserved to the route.
        quantity = min(10, max(0, int(shed.get(item, 0))))
        if quantity == 0:
            continue
        stock = _get(inventory, item, _params(item, obs, configuration)["I0"])
        value, _ = _sale_value(item, stock, quantity, obs, configuration)
        incoming = state["supply"].get(item, 0)
        future_demand = sum(_demand_on_tick(obs, configuration, t)[item] for t in range(step, step + 4))
        later, _ = _sale_value(item, stock + incoming - future_demand, quantity, obs, configuration)
        preempt = state["mode"] == "COLLISION" and value - later >= max(5, 0.02 * value)
        threshold = 1.0 if state["mode"] == "PATIENCE" else 0.6
        after_demand = consumed[item] > 0 and value / quantity >= threshold * _params(item, obs, configuration)["base"]
        if not (preempt or after_demand):
            continue
        if not preempt:
            quantity = min(quantity, 2 * consumed[item])
        candidates.append((value - later, value, ["SELL", item, quantity]))
    candidates.sort(key=lambda row: row[:2], reverse=True)
    limit = max(1, int(_get(configuration, "maxMarketOrdersPerTurn", 10)))
    result["market"] = [row[2] for row in candidates[:limit]]
    state["extra_orders"] += len(result["market"])
    return result


def _final_liquidation(obs, action, configuration):
    result = _copy_action(action)
    shed = _project_shed(obs, result, configuration)
    inventory = _get(_get(obs, "market", {}), "inventory", {})
    orders = [["SELL", item, int(shed[item])] for item in _MARKET_PARAMS if shed.get(item, 0) > 0]
    orders.sort(key=lambda o: _sale_value(o[1], _get(inventory, o[1], 10000), o[2], obs, configuration)[0], reverse=True)
    limit = max(1, int(_get(configuration, "maxMarketOrdersPerTurn", 10)))
    result["market"] = orders[:limit]
    return result


def agent(obs, configuration=None):
    step = max(0, int(_get(obs, "step", 0) or 0))
    route_step = min(step, len(_LEGACY_ACTIONS) - 1)
    action = _align_hands(_LEGACY_ACTIONS[route_step], obs)
    # Track errors per stage for tests/benchmarks without writing to stdout.
    state = _MARKET_STATE.setdefault(_seat(obs), {"last_step": -1, "errors": {}})
    for stage in ("expert", "weed", "market"):
        try:
            if stage == "expert":
                if "mode" not in state:
                    _MARKET_STATE.pop(_seat(obs), None)
                state = _update_expert(obs, configuration)
            elif stage == "weed":
                action = _weed_repair_action(obs, action, _LEGACY_ACTIONS, step)
            else:
                if step == max(0, int(_get(configuration, "episodeSteps", 720)) - 2):
                    action = _final_liquidation(obs, action, configuration)
                # Selected ablation: a persistent public clone signal advances
                # our own known sale by two ticks, then repays that exact amount.
                # Post-demand deferral, idle sales, and the new run sorter remain
                # available for experiments but are deliberately not active.
                proposed_state = copy.deepcopy(state)
                action = _clone_route_preemption(
                    obs, action, configuration, proposed_state, _LEGACY_ACTIONS
                )
                action = _jet1_rank_sell_slots(obs, action, configuration)
                state.clear()
                state.update(proposed_state)
        except Exception:
            state["errors"][stage] = state["errors"].get(stage, 0) + 1
    return _align_hands(action, obs)


def _kaggle_submission_entrypoint(obs, configuration=None):
    return agent(obs, configuration)
