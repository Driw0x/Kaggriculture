def _params(item, obs=None, configuration=None):
    result = dict(zip(_PARAM_FIELDS, _MARKET_PARAMS[item]))
    # Configuration can contain sparse overrides. The observation contains the
    # engine's effective parameters and takes precedence when present.
    for overrides in (_get(configuration, "marketParams", {}),
                      _get(_get(obs, "market", {}), "params", {})):
        patch = _get(overrides, item, {})
        if isinstance(patch, dict):
            result.update(patch)
    return result


def _shape(name, value, scale=None):
    value = max(0.0, float(value))
    if name == "sq":
        return value * value
    if name == "sqrt":
        return math.sqrt(value)
    if name == "log":
        return math.log(1.0 + value)
    if name == "log10":
        return math.log10(1.0 + value)
    if name == "hinge" and scale and scale > 0:
        ratio = value / scale
        return ratio + 8.0 * max(0.0, ratio - 1.0) ** 2
    return value


def _market_price(item, inventory, obs=None, configuration=None):
    p = _params(item, obs, configuration)
    return _price_with_params(p, inventory)


def _price_with_params(p, inventory):
    side = "below" if inventory < p["I0"] else "above"
    shape = p[side + "_func"]
    amplitude = p[side + "_target"] * p["base"] / _shape(shape, p["T"], p["T"])
    change = amplitude * _shape(shape, abs(inventory - p["I0"]), p["T"])
    return max(_PRICE_FLOOR, int(round(p["base"] + (change if side == "below" else -change))))


def _sale_value(item, inventory, quantity, obs=None, configuration=None):
    """Unit-by-unit proceeds and supply; floor-price sales do not add supply."""
    value = 0
    params = _params(item, obs, configuration)
    for _ in range(max(0, int(quantity))):
        quote = _price_with_params(params, inventory)
        value += quote
        if quote > _PRICE_FLOOR:
            inventory += 1
    return value, inventory


def _demand_on_tick(obs, configuration, tick):
    demand = {item: 0 for item in _MARKET_PARAMS}
    if tick < 0:
        return demand
    shop_interval = max(1, int(_get(configuration, "townShopSellInterval", 4)))
    center_interval = max(1, int(_get(configuration, "townCenterSellInterval", 24)))
    if tick % shop_interval == 0:
        for shop in _get(_get(obs, "town", {}), "unlocked_shops", []) or []:
            products = _SHOP_PRODUCTS.get(shop, ())
            for item in products:
                demand[item] += 2 if len(products) == 1 else 1
    if tick % center_interval == 0:
        for item in demand:
            if item != "FERTILIZER":
                demand[item] += 1
    return demand


